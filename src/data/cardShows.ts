// Coords are approximate city-centre / venue lat-lng — used for the
// upcoming "distance from your city" search on the listing pages.

export type CardShowCountry = 'uk' | 'us' | 'ca' | 'au' | 'nz'

export interface CardShow {
  id: string
  name: string
  slug: string
  country: CardShowCountry
  region: string
  city: string
  venue?: string
  address?: string
  /** UK postcode / US ZIP / CA postal code / AU postcode / NZ postcode. */
  postcode?: string
  startDate: string                 // ISO yyyy-mm-dd
  endDate?: string                  // ISO yyyy-mm-dd, omit for single-day
  recurring?: string                // e.g. "monthly", "first sunday of the month"
  eventType: 'pokemon' | 'tcg' | 'card-show' | 'collectibles' | 'mixed'
  description: string
  organiserName?: string
  websiteUrl?: string
  ticketUrl?: string
  instagramUrl?: string
  facebookUrl?: string
  imageUrl?: string                 // logo / hero image
  /**
   * Optional URL for the image source (organiser's own graphic /
   * ticket page hero). Never a hotlinked file we downloaded — image
   * provenance is left as a source link only. Populated visually in
   * Block 54B, not here.
   */
  imageSourceUrl?: string
  latitude?: number                 // approx venue lat (for distance feature)
  longitude?: number                // approx venue lng
  featured?: boolean
  lastChecked: string               // ISO yyyy-mm-dd
  status: 'upcoming' | 'cancelled' | 'past' | 'unknown'
  /**
   * Where we sourced or verified this entry from. When distinct
   * from `websiteUrl`, this points at the specific listing page
   * (e.g. an event calendar or ticket page) rather than the
   * organiser home. Optional so pre-54A entries are not touched.
   */
  sourceUrl?: string
}

